CREATE OR REPLACE VIEW public.vw_admin_transaction_complete AS
SELECT
    t.id AS transaction_id,
    COALESCE(t.transaction_ref, '') AS transaction_ref,
    COALESCE(t.transaction_type, '') AS transaction_type,
    COALESCE(t.payment_method, '') AS payment_method,
    COALESCE(t.gateway_name, '') AS gateway_name,
    COALESCE(t.amount, 0) AS amount,
    COALESCE(t.currency, 'INR') AS currency,
    COALESCE(t.status, '') AS transaction_status,
    COALESCE(u."Name", '') AS user_name,
    COALESCE(u."Email", '') AS user_email,
    COALESCE(b.booking_ref, '') AS booking_ref,
    COALESCE(b.booking_status, '') AS booking_status,
    COALESCE(b.total_amount, 0) AS total_amount,
    COALESCE(b.discount_amount, 0) AS discount_amount,
    COALESCE(b.tax_amount, 0) AS tax_amount,
    COALESCE(b.payable_amount, 0) AS payable_amount,
    COALESCE(c.coupon_code, '') AS coupon_code,
    COALESCE(sch."Type", '') AS show_type,
    COALESCE(m."Title", ssu."Title", ls."Title", '') AS show_title,
    COALESCE(loc."Country", '') AS country,
    COALESCE(loc."State", '') AS state,
    COALESCE(loc."Area", '') AS area,
    COALESCE(r.refund_status, '') AS refund_status,
    r.refund_amount,
    t.created_at
FROM public.transactions t
LEFT JOIN public.bookings b ON t.booking_id = b.id OR b.transaction_id = t.id
LEFT JOIN public."Users" u ON COALESCE(b.user_id, t.user_id) = u."Id"
LEFT JOIN public."ShowSchedules" sch ON b.schedule_id = sch."Id"
LEFT JOIN public."Movies" m ON sch."MovieId" = m."Id"
LEFT JOIN public."StandupShows" ssu ON sch."StandupShowId" = ssu."Id"
LEFT JOIN public."LiveStreams" ls ON sch."LiveStreamId" = ls."Id"
LEFT JOIN public."Locations" loc ON sch."LocationId" = loc."Id"
LEFT JOIN public.refunds r ON t.id = r.transaction_id
LEFT JOIN public.coupons c ON b.coupon_id = c.id;

