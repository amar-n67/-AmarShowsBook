-- AmarShowsBook enterprise schema rebuild script
-- Run on an empty PostgreSQL database.
-- Order: extensions -> functions -> tables -> foreign keys -> indexes -> triggers -> seed data -> views.

BEGIN;

SET check_function_bodies = off;

CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE SEQUENCE IF NOT EXISTS public.booking_ref_seq START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE IF NOT EXISTS public.refund_ref_seq START WITH 1 INCREMENT BY 1;

CREATE OR REPLACE FUNCTION public.fn_update_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.fn_set_booking_reference()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.booking_ref IS NULL OR btrim(NEW.booking_ref) = '' THEN
        NEW.booking_ref := 'BK' || to_char(CURRENT_TIMESTAMP, 'YYYYMMDD') || lpad(nextval('public.booking_ref_seq')::text, 6, '0');
    END IF;

    IF NEW.original_amount IS NULL THEN
        NEW.original_amount := NEW.total_amount;
    END IF;

    IF NEW.payable_amount IS NULL THEN
        NEW.payable_amount := GREATEST(
            COALESCE(NEW.total_amount, 0)
            + COALESCE(NEW.tax_amount, 0)
            + COALESCE(NEW.convenience_fee, 0)
            - COALESCE(NEW.discount_amount, 0)
            - COALESCE(NEW.wallet_amount_used, 0),
            0
        );
    END IF;

    IF NEW.payment_status IS NULL THEN
        NEW.payment_status := 'PENDING';
    END IF;

    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.fn_track_booking_status()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF OLD.booking_status IS DISTINCT FROM NEW.booking_status THEN
        INSERT INTO public.booking_status_history
            (booking_id, old_status, new_status, changed_by, remarks, created_at)
        VALUES
            (NEW.id, OLD.booking_status, NEW.booking_status, COALESCE(NEW.updated_by, CURRENT_USER), 'Booking status changed', CURRENT_TIMESTAMP);

        INSERT INTO public.booking_history
            (booking_id, user_id, action, old_status, new_status, old_value, new_value, remarks, created_at)
        VALUES
            (NEW.id, NEW.user_id, 'STATUS_CHANGED', OLD.booking_status, NEW.booking_status, to_jsonb(OLD), to_jsonb(NEW), 'Booking status changed', CURRENT_TIMESTAMP);
    END IF;

    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.fn_assign_default_role()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_role_id bigint;
BEGIN
    SELECT id INTO v_role_id
    FROM public.roles
    WHERE role_code = 'USER'
    LIMIT 1;

    IF v_role_id IS NOT NULL THEN
        INSERT INTO public.user_roles (user_id, role_id, assigned_by, is_active)
        VALUES (NEW."Id", v_role_id, NULL, true)
        ON CONFLICT DO NOTHING;

        INSERT INTO public.user_role_mappings (user_id, role_id, assigned_by, is_active)
        VALUES (NEW."Id", v_role_id, NULL, true)
        ON CONFLICT DO NOTHING;
    END IF;

    INSERT INTO public.user_wallets (user_id, wallet_balance, blocked_balance, loyalty_points, wallet_status)
    VALUES (NEW."Id", 0, 0, 0, 'ACTIVE')
    ON CONFLICT (user_id) DO NOTHING;

    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.fn_refund_audit()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    INSERT INTO public.refund_history
        (refund_id, refund_status_old, refund_status_new, remarks, changed_by, metadata, created_at)
    VALUES
        (NEW.id, OLD.refund_status, NEW.refund_status, COALESCE(NEW.admin_notes, NEW.approval_remarks), COALESCE(NEW.updated_by, CURRENT_USER), to_jsonb(NEW), CURRENT_TIMESTAMP);

    INSERT INTO public.refund_action_logs
        (refund_id, refund_ref, action_name, action_by, action_time, action_notes)
    VALUES
        (NEW.id, NEW.refund_ref, COALESCE(NEW.workflow_action, NEW.refund_status), COALESCE(NEW.updated_by, CURRENT_USER), CURRENT_TIMESTAMP, COALESCE(NEW.admin_notes, NEW.failure_reason));

    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.fn_wallet_balance_update()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF COALESCE(NEW.status, NEW.transaction_status, 'SUCCESS') = 'SUCCESS' THEN
        UPDATE public.user_wallets
        SET wallet_balance =
                CASE
                    WHEN NEW.entry_type = 'CREDIT' THEN wallet_balance + NEW.amount
                    WHEN NEW.entry_type = 'DEBIT' THEN GREATEST(wallet_balance - NEW.amount, 0)
                    ELSE wallet_balance
                END,
            last_transaction_at = CURRENT_TIMESTAMP,
            updated_at = CURRENT_TIMESTAMP
        WHERE id = NEW.wallet_id;
    END IF;

    RETURN NEW;
END;
$$;

