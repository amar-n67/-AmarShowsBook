SELECT t.id, 'TRANSACTION', t.status, u."Name", u."Email", t.transaction_ref, t.status,
       COALESCE(t.description, 'Transaction processed'), t.failure_reason, COALESCE(t.completed_at, t.created_at)
FROM public.transactions t
LEFT JOIN public."Users" u ON u."Id" = t.user_id
UNION ALL
SELECT b.id, 'BOOKING', b.booking_status, u."Name", u."Email", b.booking_ref, b.booking_status,
       'Ticket booking activity', NULL::text, b.created_at
FROM public.bookings b
LEFT JOIN public."Users" u ON u."Id" = b.user_id
UNION ALL
SELECT al.id::bigint, 'SYSTEM', al.action::varchar, u."Name", u."Email", NULL::text, al.status::varchar,
       al.description, al.error_message, al.created_at
FROM public.activity_logs al
LEFT JOIN public."Users" u ON u."Id" = al.user_id;

